-- =====================================================================
-- RadarBajet — skema Supabase (jalankan dalam SQL Editor, satu kali)
-- =====================================================================
-- Perbezaan penting berbanding cadangan dalam perbualan asal:
--   * Row Level Security (RLS) DIDAYAKAN pada semua jadual.
--     Tanpa RLS, anon key yang tertanam dalam app bermakna sesiapa
--     boleh baca, ubah dan PADAM semua harga anda.
--   * Tiada lajur "status_kedai" bercampur dengan harga.
--     Bukti & sumber harga disimpan pada baris harga, bukan pada kedai.
--   * Harga pengguna tidak boleh dipadam oleh peniaga.
-- =====================================================================

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------
-- 1. PROFIL
-- ---------------------------------------------------------------------
create table if not exists public.profil (
    id          uuid primary key references auth.users (id) on delete cascade,
    email       text,
    peranan     text not null default 'consumer'
                check (peranan in ('consumer', 'merchant', 'admin')),
    mata        integer not null default 0 check (mata >= 0),
    created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 2. KEDAI
-- ---------------------------------------------------------------------
create table if not exists public.kedai (
    id          bigint generated by default as identity primary key,
    nama        text not null check (length(trim(nama)) between 2 and 120),
    kategori    text,
    lat         double precision not null check (lat between -90 and 90),
    lon         double precision not null check (lon between -180 and 180),
    status      text not null default 'unclaimed'
                check (status in ('unclaimed', 'verified')),
    pemilik_id  uuid references auth.users (id) on delete set null,
    konteks     text,
    created_at  timestamptz not null default now()
);

create index if not exists kedai_latlon_idx on public.kedai (lat, lon);

-- ---------------------------------------------------------------------
-- 3. HARGA (setiap baris = satu laporan)
-- ---------------------------------------------------------------------
create table if not exists public.harga (
    id            bigint generated by default as identity primary key,
    kedai_id      bigint not null references public.kedai (id) on delete cascade,
    item          text not null check (length(trim(item)) >= 2),
    kategori      text,
    harga         numeric(10, 2) not null check (harga > 0 and harga < 100000),
    sumber        text not null default 'resit'
                  check (sumber in ('resit', 'peniaga', 'admin')),
    bukti_path    text,
    dilapor_oleh  uuid references auth.users (id) on delete set null,
    created_at    timestamptz not null default now()
);

create index if not exists harga_kedai_idx on public.harga (kedai_id, created_at desc);
create index if not exists harga_item_idx on public.harga (lower(item));

-- =====================================================================
-- 4. RLS
-- =====================================================================
alter table public.profil enable row level security;
alter table public.kedai enable row level security;
alter table public.harga enable row level security;

-- GRANT: RLS menyaring baris, GRANT memberi akses jadual. Kedua-duanya perlu.
-- Tanpa blok ini, PostgREST pulangkan 42501 "permission denied for table".
grant usage on schema public to anon, authenticated;

grant select on public.kedai to anon;
grant select on public.harga to anon;

grant select on public.kedai to authenticated;
grant insert, update on public.kedai to authenticated;

grant select on public.harga to authenticated;
grant insert, delete on public.harga to authenticated;

-- UPDATE profil dihadkan kepada lajur mata & email sahaja.
-- Tanpa sekatan ini, pengguna boleh set peranan='merchant' pada diri sendiri
-- dan terbit harga bertanda "Peniaga".
grant select on public.profil to authenticated;
grant insert on public.profil to authenticated;
grant update (mata, email) on public.profil to authenticated;

grant usage, select on all sequences in schema public to authenticated;

-- ---- profil ----
drop policy if exists profil_baca_sendiri  on public.profil;
drop policy if exists profil_cipta_sendiri on public.profil;
drop policy if exists profil_kemas_sendiri on public.profil;

create policy profil_baca_sendiri  on public.profil for select using (auth.uid() = id);
create policy profil_cipta_sendiri on public.profil for insert with check (auth.uid() = id);
-- Pengguna hanya boleh ubah profil sendiri, dan hanya lajur mata/email
create policy profil_kemas_sendiri on public.profil for update
    using (auth.uid() = id) with check (auth.uid() = id);

-- ---- kedai ----
drop policy if exists kedai_baca_semua     on public.kedai;
drop policy if exists kedai_cipta_ahli     on public.kedai;
drop policy if exists kedai_kemas_pemilik  on public.kedai;

create policy kedai_baca_semua on public.kedai for select using (true);

create policy kedai_cipta_ahli on public.kedai for insert
    to authenticated with check (auth.uid() = pemilik_id);

create policy kedai_kemas_pemilik on public.kedai for update
    to authenticated
    using (auth.uid() = pemilik_id)
    with check (auth.uid() = pemilik_id and status = 'unclaimed');
    -- nota: status='verified' hanya boleh diset oleh admin melalui service role,
    -- supaya peniaga tidak boleh beri lencana "disahkan" kepada diri sendiri.

-- ---- harga ----
drop policy if exists harga_baca_semua   on public.harga;
drop policy if exists harga_cipta_ahli   on public.harga;
drop policy if exists harga_padam_pelapor on public.harga;

create policy harga_baca_semua on public.harga for select using (true);

create policy harga_cipta_ahli on public.harga for insert
    to authenticated with check (
        auth.uid() = dilapor_oleh
        and harga > 0
        -- peniaga hanya boleh terbit 'peniaga'; pengguna hanya 'resit'
        and (
            (sumber = 'resit'    and exists (select 1 from public.profil p where p.id = auth.uid() and p.peranan in ('consumer', 'merchant', 'admin')))
            or
            (sumber = 'peniaga'  and exists (select 1 from public.profil p where p.id = auth.uid() and p.peranan in ('merchant', 'admin')))
        )
    );

-- Pelapor boleh tarik balik laporan sendiri. Tiada siapa lain boleh padam.
create policy harga_padam_pelapor on public.harga for delete
    to authenticated using (auth.uid() = dilapor_oleh);

-- =====================================================================
-- 5. STORAGE BUKTI (bucket peribadi)
-- =====================================================================
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('resit', 'resit', false, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
    set public             = excluded.public,
        file_size_limit    = excluded.file_size_limit,
        allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists resit_muat_naik on storage.objects;
drop policy if exists resit_baca_sendiri on storage.objects;

create policy resit_muat_naik on storage.objects for insert
    to authenticated with check (
        bucket_id = 'resit'
        and (storage.foldername(name))[1] = auth.uid()::text
    );

create policy resit_baca_sendiri on storage.objects for select
    to authenticated using (
        bucket_id = 'resit'
        and (storage.foldername(name))[1] = auth.uid()::text
    );

-- =====================================================================
-- 6. TRIGGER: cipta profil automatik selepas sign_up
--    (lebih selamat daripada insert dari klien, yang mudah gagal
--     bila sesi belum aktif)
-- =====================================================================
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.profil (id, email, peranan, mata)
    values (
        new.id,
        new.email,
        coalesce(new.raw_user_meta_data ->> 'peranan', 'consumer'),
        10
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

